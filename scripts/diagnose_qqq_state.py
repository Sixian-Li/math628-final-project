"""Diagnostics and figures for the QQQ market-state filter (reference configuration).

Reference configuration (fixed, not chosen from results): base rule SMA20/140, features new+cross,
1-week target, ridge10, hold when the forecast is > 0. See scripts/run_qqq_state.py.

Writes results/qqq_state/QQQ_sma20_140/diagnostics.md and figures/:
  1. kept vs dropped weeks: mean next-week return, t-test, forecast/return correlation
  2. the same by calendar year (sign test)
  3. feature-lag test (features delayed by 1, 2, 4 weeks)
  4. cost sensitivity
  5. which feature block carries the result
  6. standardized coefficients of the final fit
  7. the QQQ-trained signal applied to XLK, SPY and IWM
  8. equity curves and yearly kept/dropped chart
Usage: .venv/bin/python scripts/diagnose_qqq_state.py
"""

from __future__ import annotations

import sys
import warnings
from math import comb
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))
warnings.filterwarnings("ignore")

import run_qqq_state as R  # noqa: E402
from ml_filter.backtest import equity_curve, metrics  # noqa: E402
from ml_filter.data import load_daily, weekly_table  # noqa: E402
from ml_filter.meta import sma_windows  # noqa: E402
from ml_filter.universe import build_panel  # noqa: E402
from ml_filter.xfeat import FEATURE_SETS as FS  # noqa: E402
from ml_filter.xfeat import market_features  # noqa: E402
from run_experiments import md_table  # noqa: E402

OUT = ROOT / "results" / "qqq_state" / "QQQ_sma20_140"
FE = R.FEATS["new+cross"]


def main():
    (OUT / "figures").mkdir(parents=True, exist_ok=True)
    P = build_panel()
    X = market_features(P, sma_windows(P, [1, 50, 140, 200]))
    D = load_daily("QQQ")
    W = weekly_table(D)
    X["year"] = W.year.to_numpy()
    fd = W.groupby("year")["d"].min().to_dict()
    base = (X.slow_up == 1).to_numpy()
    r = X.R1.to_numpy()

    def curve(w, y0, y1, cost=5):
        ev = W[W.year.between(y0, y1) & (W.e_next <= pd.Timestamp(f"{y1}-12-31"))]
        return equity_curve(D, ev, w[ev.index].astype(float), cost)

    def perf(w, y0, y1, cost=5):
        m = metrics(curve(w, y0, y1, cost))
        return {"cagr": m["cagr_pct"], "hold_cagr": m["holding_cagr_pct"], "maxdd": m["max_dd_pct"], "sharpe": m["sharpe"], "exposure": m["exposure_pct"], "trades_py": m["trades_per_year"]}

    def keep_of(Xm, feats, mk="ridge10", h=1):
        pred, _, _ = R.walk(Xm, base, feats, h, mk, fd)
        return base & (pred > 0), pred

    k, pred = keep_of(X, FE)
    L = ["# QQQ market-state filter: diagnostics (auto-generated by scripts/diagnose_qqq_state.py)", "", __doc__.split("Writes")[0]]

    rows = []
    for nm, w in {"buy and hold": np.ones(len(X), bool), "base rule SMA20/140": base, "base + ML filter": k}.items():
        rows.append({"rule": nm, **{f"{m}_{p}": v for p, (a, b) in R.PERIODS.items() for m, v in perf(w, a, b).items() if m != "trades_py"}})
    L += ["## 0. Performance, 5 bps", "", md_table(pd.DataFrame(rows)), ""]

    rows = []
    for pn, (a, b) in R.PERIODS.items():
        m = base & X.year.between(a, b).to_numpy() & np.isfinite(pred)
        kk, dd = r[m & k], r[m & ~k]
        t = (kk.mean() - dd.mean()) / np.sqrt(kk.var(ddof=1) / len(kk) + dd.var(ddof=1) / len(dd))
        c = np.corrcoef(pred[m], r[m])[0, 1]
        rows.append({"period": pn, "kept_weeks": len(kk), "kept_mean_bps": kk.mean() * 1e4, "kept_up_pct": (kk > 0).mean() * 100, "dropped_weeks": len(dd),
                     "dropped_mean_bps": dd.mean() * 1e4, "dropped_up_pct": (dd > 0).mean() * 100, "diff_t": t, "corr_forecast_return": c, "corr_t": c * np.sqrt(m.sum() - 2) / np.sqrt(1 - c * c)})
    L += ["## 1. Kept vs dropped base-rule weeks: next-week open-to-open return", "", md_table(pd.DataFrame(rows)), ""]

    yr = pd.DataFrame({"year": X.year, "base": base, "keep": k, "R": r})
    yr = yr[yr.base & yr.year.between(2005, 2025)]
    by = yr.groupby("year").apply(lambda g: pd.Series({"kept": int(g.keep.sum()), "dropped": int((~g.keep).sum()), "kept_bps": g.R[g.keep].mean() * 1e4,
                                                         "dropped_bps": g.R[~g.keep].mean() * 1e4}), include_groups=False).reset_index()
    by["kept_better"] = by.kept_bps > by.dropped_bps
    n, w_ = len(by), int(by.kept_better.sum())
    p_sign = sum(comb(n, i) for i in range(w_, n + 1)) / 2 ** n
    L += ["## 2. By calendar year", "", md_table(by, "{:.1f}"), "", f"Kept weeks beat dropped weeks in {w_} of {n} years (one-sided sign test p = {p_sign:.4f}).", ""]

    rows = []
    for lag in (0, 1, 2, 4):
        Xl = X.copy()
        Xl[FE] = X[FE].shift(lag)
        kl, _ = keep_of(Xl, FE)
        rows.append({"feature_lag_weeks": lag, **{f"{m}_{p}": v for p, (a, b) in R.PERIODS.items() for m, v in perf(kl, a, b).items() if m in ("cagr", "hold_cagr", "exposure")}})
    L += ["## 3. Feature-lag test (stale features should weaken the filter)", "", md_table(pd.DataFrame(rows)), ""]

    rows = [{"cost_bps": c, "base_cagr": perf(base, 2005, 2025, c)["cagr"], "base_hold_cagr": perf(base, 2005, 2025, c)["hold_cagr"], **perf(k, 2005, 2025, c)} for c in (0, 5, 10, 20)]
    L += ["## 4. Cost sensitivity, 2005-2025", "", md_table(pd.DataFrame(rows)), ""]

    rows = []
    for nm, fe in {"all 16 (reference)": FE, "VIX block": FS["vix"], "breadth block": FS["breadth"], "cross-asset block": FS["cross"], "VIX + breadth": FS["vix"] + FS["breadth"],
                   "original 7 price features": FS["price7"], "QQQ 5-day return alone": ["ret5"]}.items():
        kb, _ = keep_of(X, fe)
        rows.append({"features": nm, **{f"{m}_{p}": v for p, (a, b) in R.PERIODS.items() for m, v in perf(kb, a, b).items() if m in ("cagr", "hold_cagr", "exposure")}})
    L += ["## 5. Which feature block carries the result (ridge10, 1-week target, forecast > 0)", "", md_table(pd.DataFrame(rows)), ""]

    tr = base & (X.year >= 2000).to_numpy() & np.isfinite(r) & (X.t1 <= fd[2025]).to_numpy()
    co = pd.DataFrame({mk: R.MODELS[mk]().fit(X.loc[tr, FE], r[tr] / r[tr].std())[-1].coef_ for mk in ("ridge10", "lasso")}, index=FE).sort_values("ridge10")
    L += ["## 6. Standardized coefficients of the last fit (training through 2024; target in standard deviations)", "", md_table(co.reset_index().rename(columns={"index": "feature"}), "{:.3f}"), ""]
    # 7. the QQQ-trained forecast applied to other assets' own SMA20/140 weeks (same signal, different traded asset)
    predall = np.full(len(X), np.nan)
    A = X[FE].to_numpy()
    for y_ in R.YEARS:
        trn = base & (X.year >= 2000).to_numpy() & np.isfinite(r) & (X.t1 <= fd[y_]).to_numpy()
        te = (X.year == y_).to_numpy()
        predall[te] = R.MODELS["ridge10"]().fit(A[trn], r[trn] / r[trn].std()).predict(A[te])
    sig = pd.Series(predall > 0, index=X.d)
    rows = []
    for sym in ("QQQ", "XLK", "SPY", "IWM"):
        Ds = load_daily(sym)
        Ws = weekly_table(Ds)
        c = Ds.set_index("date")["close"]
        b = ((c.rolling(20).mean() > c.rolling(140).mean()) & c.rolling(140).mean().notna()).reindex(Ws.d).to_numpy()
        kq = b & sig.reindex(Ws.d).fillna(False).to_numpy()
        for nm, w in (("base rule", b), ("base + QQQ-trained filter", kq)):
            row = {"asset": sym, "rule": nm}
            for pn, (a, b_) in R.PERIODS.items():
                ev = Ws[Ws.year.between(a, b_) & (Ws.e_next <= pd.Timestamp(f"{b_}-12-31"))]
                m = metrics(equity_curve(Ds, ev, w[ev.index].astype(float), 5))
                row.update({f"cagr_{pn}": m["cagr_pct"], f"hold_cagr_{pn}": m["holding_cagr_pct"], f"sharpe_{pn}": m["sharpe"], f"exposure_{pn}": m["exposure_pct"]})
            rows.append(row)
    L += ["## 7. The QQQ-trained signal applied to other assets (each asset keeps its own SMA20/140 weeks)", "", md_table(pd.DataFrame(rows)), "",
          "These assets are highly correlated with QQQ, so this is not independent confirmation.", ""]
    (OUT / "diagnostics.md").write_text("\n".join(L))

    # ---- figures
    fig, (a1, a2) = plt.subplots(2, 1, figsize=(11, 7.5), sharex=True, gridspec_kw={"height_ratios": [3, 1.2]})
    for nm, w, col in (("QQQ buy and hold", np.ones(len(X), bool), "0.55"), ("SMA20/140 (base rule)", base, "C0"), ("SMA20/140 + ML market-state filter", k, "C3")):
        cv = curve(w, 2005, 2025)
        d = pd.to_datetime(cv.date)
        m = metrics(cv)
        a1.plot(d, cv.equity, color=col, lw=1.4, label=f"{nm}: CAGR {m['cagr_pct']:.1f}%, holding CAGR {m['holding_cagr_pct']:.1f}%, in market {m['exposure_pct']:.0f}%, max DD {m['max_dd_pct']:.0f}%")
        a2.plot(d, cv.equity / cv.equity.cummax().clip(lower=1) - 1, color=col, lw=0.9)
    for ax in (a1, a2):
        ax.axvline(pd.Timestamp("2019-01-01"), color="k", ls=":", lw=1)
        ax.grid(alpha=0.3)
    a1.text(pd.Timestamp("2019-03-01"), a1.get_ylim()[0] * 1.3 if a1.get_ylim()[0] > 0 else 1.0, "holdout →", fontsize=9)
    a1.set_yscale("log"); a1.set_ylabel("Growth of $1 (log)"); a1.legend(fontsize=8, loc="upper left")
    a1.set_title("QQQ: trend rule + ML filter on market-state features (ridge, 1-week target), weekly, 5 bps")
    a2.set_ylabel("Drawdown")
    fig.tight_layout(); fig.savefig(OUT / "figures" / "equity_reference.png", dpi=150); plt.close(fig)

    fig, ax = plt.subplots(figsize=(11, 4))
    xs = np.arange(len(by))
    ax.bar(xs - 0.2, by.kept_bps, 0.4, label="weeks the filter keeps", color="C3")
    ax.bar(xs + 0.2, by.dropped_bps, 0.4, label="weeks the filter drops", color="0.6")
    ax.set_xticks(xs, by.year.astype(int), rotation=45)
    ax.axhline(0, color="k", lw=0.8); ax.axvline(13.5, color="k", ls=":", lw=1)
    ax.set_ylim(-250, 150)
    ax.set_ylabel("mean next-week return (bps)"); ax.legend(fontsize=8); ax.grid(axis="y", alpha=0.3)
    ax.set_title(f"Base-rule weeks kept vs dropped by the ML filter, by year (kept better in {w_} of {n} years; bars clipped at −250)")
    fig.tight_layout(); fig.savefig(OUT / "figures" / "kept_vs_dropped_by_year.png", dpi=150); plt.close(fig)
    print("\n".join(L[:60]))


if __name__ == "__main__":
    main()
